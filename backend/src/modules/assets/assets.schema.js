const { z } = require('zod');

// An optional foreign key sent from a form that leaves it blank — "not
// room-bound", "no vendor" — arrives as the empty string, not absent. Zod's
// coercion runs before .optional()/.nullable() are checked, so
// z.coerce.number() turns '' into 0 first and .positive() then rejects it
// with its default message ("Too small: expected number to be >0"), a raw
// Zod string with no field context that has no business reaching a form.
// Stripping '' to null here, before coercion, is what makes "blank" actually
// mean "not set" instead of "an invalid number was sent".
const optionalId = (message) =>
  z.preprocess(
    (v) => (v === '' || v === undefined ? null : v),
    z.coerce.number().int().positive(message).nullable().optional()
  );

const categorySchema = z.object({
  name: z.string().trim().min(1, 'Category name is required.').max(60),
});

// Every field but name and categoryId is optional — a hotel registering fifty
// assets in one afternoon shouldn't be blocked from saving one because the
// serial number is on a sticker nobody's found yet.
//
// assetTag is absent on purpose — it's generated by the server on create and
// never accepted from the client, so a crafted request can't collide it with
// another asset's tag or overwrite one already printed on a sticker.
//
// warrantyExpiry is accepted here (createAsset/createAssetsBulk seed it as
// the asset's first Coverage-history row) but updateAsset ignores it even if
// sent — once an asset exists, warranty/AMC only change through the
// Coverage history "Add/Renew" action, never by editing the asset. There is
// no amcExpiry/amcCoverageNote here at all: AMC never exists at
// registration, only after a warranty lapses.
const assetSchema = z.object({
  name: z.string().trim().min(1, 'Asset name is required.').max(120),
  categoryId: z.coerce.number().int().positive('Choose a category.'),
  brand: z.string().trim().max(80).optional().default(''),
  model: z.string().trim().max(80).optional().default(''),
  serialNumber: z.string().trim().max(120).optional().default(''),
  purchaseDate: z.string().trim().max(10).optional().default(''),
  purchaseCost: z.coerce.number().min(0, 'Cost can’t be negative.').optional().nullable(),
  roomId: optionalId(),
  floor: z.string().trim().max(20).optional().default(''),
  department: z.string().trim().max(60).optional().default(''),
  locationNote: z.string().trim().max(200).optional().default(''),
  vendorId: optionalId(),
  warrantyExpiry: z.string().trim().max(10).optional().default(''),
});

// A single purchase — one category, one vendor, one bill, one purchase
// date/cost, one warranty/AMC — landing as several rows because a hotel
// buys equipment in lots, not one at a time. Only what actually varies per
// unit (name, room, floor, location) is asked for per unit; everything
// else here is exactly assetSchema minus the per-unit fields.
const bulkUnitSchema = z.object({
  name: z.string().trim().min(1, 'Every unit needs a name.').max(120),
  serialNumber: z.string().trim().max(120).optional().default(''),
  roomId: optionalId(),
  floor: z.string().trim().max(20).optional().default(''),
  department: z.string().trim().max(60).optional().default(''),
  locationNote: z.string().trim().max(200).optional().default(''),
});

const bulkAssetSchema = z.object({
  categoryId: z.coerce.number().int().positive('Choose a category.'),
  brand: z.string().trim().max(80).optional().default(''),
  model: z.string().trim().max(80).optional().default(''),
  purchaseDate: z.string().trim().max(10).optional().default(''),
  purchaseCost: z.coerce.number().min(0, 'Cost can’t be negative.').optional().nullable(),
  vendorId: optionalId(),
  warrantyExpiry: z.string().trim().max(10).optional().default(''),
  // 200 caps one request at something a browser and the database both
  // handle comfortably without pagination — a hotel buying more than that
  // in one purchase order is buying it in more than one delivery too.
  units: z.array(bulkUnitSchema).min(1, 'Add at least one unit.').max(200, 'That’s a lot for one batch — split it into two.'),
});

// One warranty or AMC period. end_date is the only date actually required —
// a warranty's start is the purchase date and often isn't typed twice, and a
// paper AMC contract sometimes only states when it runs out.
const coveragePeriodSchema = z.object({
  coverageType: z.enum(['WARRANTY', 'AMC'], { error: 'Choose warranty or AMC.' }),
  vendorId: optionalId(),
  startDate: z.string().trim().max(10).optional().default(''),
  endDate: z.string().trim().min(1, 'Enter when this coverage ends.').max(10),
  cost: z.coerce.number().min(0, 'Cost can’t be negative.').optional().nullable(),
  coverageNote: z.string().trim().max(200).optional().default(''),
});

const updateAssetStatusSchema = z.object({
  status: z.enum(['IN_USE', 'UNDER_REPAIR', 'TRANSFERRED', 'RETIRED'], {
    error: 'Choose a status.',
  }),
});

const vendorSchema = z.object({
  name: z.string().trim().min(1, 'Vendor name is required.').max(120),
  contactPerson: z.string().trim().max(80).optional().default(''),
  phone: z.string().trim().max(20).optional().default(''),
  email: z.string().trim().max(120).optional().default(''),
  specialty: z.string().trim().max(80).optional().default(''),
  notes: z.string().trim().max(400).optional().default(''),
});

const createWorkOrderSchema = z.object({
  assetId: z.coerce.number().int().positive('Choose an asset.'),
  issueType: z.enum(['BREAKDOWN', 'ROUTINE_SERVICE']).optional().default('BREAKDOWN'),
  description: z.string().trim().min(1, 'Describe the issue.').max(400),
  assignedToName: z.string().trim().max(80).optional().default(''),
  vendorId: optionalId(),
});

// One visit covering every asset in a category — "service all the ACs" —
// instead of filing the same work order by hand once per unit. assignedToName
// stays free text like the single-asset form; vendorId is who's doing the
// round, not who owns any one asset.
const bulkWorkOrderSchema = z.object({
  categoryId: z.coerce.number().int().positive('Choose a category.'),
  issueType: z.enum(['BREAKDOWN', 'ROUTINE_SERVICE']).optional().default('ROUTINE_SERVICE'),
  description: z.string().trim().min(1, 'Describe the work.').max(400),
  assignedToName: z.string().trim().max(80).optional().default(''),
  vendorId: optionalId(),
});

// Everything on a work order can be edited after it's opened — cost figures
// and the assignment are usually filled in after the fact, not at creation.
const updateWorkOrderSchema = z.object({
  status: z.enum(['OPEN', 'IN_PROGRESS', 'CLOSED']).optional(),
  issueType: z.enum(['BREAKDOWN', 'ROUTINE_SERVICE']).optional(),
  description: z.string().trim().min(1).max(400).optional(),
  assignedToName: z.string().trim().max(80).optional(),
  vendorId: optionalId(),
  partsCost: z.coerce.number().min(0).optional().nullable(),
  laborCost: z.coerce.number().min(0).optional().nullable(),
  partsUsedNote: z.string().trim().max(400).optional(),
  isWarrantyClaim: z.boolean().optional(),
  resolutionNote: z.string().trim().max(400).optional(),
});

module.exports = {
  categorySchema,
  assetSchema,
  bulkAssetSchema,
  coveragePeriodSchema,
  updateAssetStatusSchema,
  vendorSchema,
  createWorkOrderSchema,
  bulkWorkOrderSchema,
  updateWorkOrderSchema,
};
