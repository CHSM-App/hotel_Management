import '../models/quote.dart';

/// What a stay costs, worked out on the device.
///
/// A line-for-line port of the server's `pricing.service.js` (`priceNight`,
/// `simulateRange`, `normalizeSelections`) and `bookings.service.js`
/// (`priceStay`, `spreadConcession`) — the code behind GET /bookings/price-quote.
/// It exists so a booking can be quoted with no network at all, and it must
/// agree with the server to the paisa: a guest quoted ₹9,583.56 offline and
/// asked for ₹9,583.57 when the booking syncs is a guest who stops trusting the
/// desk. test/fixtures/pricing_golden.json is generated by running the
/// server's own functions over a few hundred scenarios, and
/// test/pricing_golden_test.dart requires an exact match.
///
/// Common path only: one ordinary room (no dormitory beds, no multi-room).
/// Those throw [PricingUnsupported] and the booking screen says they need a
/// connection.

class PricingUnsupported implements Exception {
  final String message;
  PricingUnsupported(this.message);
  @override
  String toString() => message;
}

class PricingSeason {
  final String name;
  final num percent;
  final String startDate;
  final String endDate;

  const PricingSeason({
    required this.name,
    required this.percent,
    required this.startDate,
    required this.endDate,
  });

  factory PricingSeason.fromJson(Map<String, dynamic> j) => PricingSeason(
    name: j['name']?.toString() ?? '',
    percent: (j['percent'] as num?) ?? 0,
    startDate: j['startDate'].toString().substring(0, 10),
    endDate: j['endDate'].toString().substring(0, 10),
  );
}

class PricingCharge {
  final int id;
  final String name;
  final num chargePerNight;
  final bool isCounter;
  final int? hiddenWhenChargeId;

  const PricingCharge({
    required this.id,
    required this.name,
    required this.chargePerNight,
    this.isCounter = false,
    this.hiddenWhenChargeId,
  });

  factory PricingCharge.fromJson(Map<String, dynamic> j) => PricingCharge(
    id: int.parse('${j['id']}'),
    name: j['name']?.toString() ?? '',
    chargePerNight: (j['chargePerNight'] as num?) ?? 0,
    isCounter: j['isCounter'] == true || j['isCounter'] == 1,
    hiddenWhenChargeId: j['hiddenWhenChargeId'] == null
        ? null
        : int.tryParse('${j['hiddenWhenChargeId']}'),
  );
}

/// "Which extra, how many of it, and at what agreed price" — see the server's
/// normalizeSelections.
class ChargePick {
  final int id;
  final int quantity;
  final double? agreedAmount;

  const ChargePick(this.id, this.quantity, [this.agreedAmount]);
}

/// JS `Math.round(n * 100) / 100`. Dart's own `round()` rounds half away from
/// zero where JS rounds half toward +infinity; they differ on negative ties,
/// and a season discount line is negative.
double round2(num n) => ((n * 100) + 0.5).floorToDouble() / 100;

/// `₹1,234.56` — Indian grouping, no trailing zeros, as the server prints it
/// into a bill line's label (`toLocaleString('en-IN', {maximumFractionDigits: 2})`).
String money(num amount) {
  final fixed = amount.toDouble().toStringAsFixed(2);
  final dot = fixed.indexOf('.');
  var whole = fixed.substring(0, dot);
  var frac = fixed.substring(dot + 1).replaceFirst(RegExp(r'0+$'), '');
  final negative = whole.startsWith('-');
  if (negative) whole = whole.substring(1);
  if (whole.length > 3) {
    var rest = whole.substring(0, whole.length - 3);
    final last = whole.substring(whole.length - 3);
    final groups = <String>[];
    while (rest.length > 2) {
      groups.insert(0, rest.substring(rest.length - 2));
      rest = rest.substring(0, rest.length - 2);
    }
    if (rest.isNotEmpty) groups.insert(0, rest);
    whole = '${groups.join(',')},$last';
  }
  return '₹${negative ? '-' : ''}$whole${frac.isEmpty ? '' : '.$frac'}';
}

List<String> datesInRange(String checkIn, String checkOut) {
  final out = <String>[];
  var cur = DateTime.utc(
    int.parse(checkIn.substring(0, 4)),
    int.parse(checkIn.substring(5, 7)),
    int.parse(checkIn.substring(8, 10)),
  );
  final end = DateTime.utc(
    int.parse(checkOut.substring(0, 4)),
    int.parse(checkOut.substring(5, 7)),
    int.parse(checkOut.substring(8, 10)),
  );
  while (cur.isBefore(end)) {
    out.add(cur.toIso8601String().substring(0, 10));
    cur = cur.add(const Duration(days: 1));
  }
  return out;
}

class _Line {
  final String label;
  final double amount;
  final bool isBase;
  final int? chargeId;
  final int? quantity;
  const _Line(this.label, this.amount, {this.isBase = false, this.chargeId, this.quantity});
}

class _Night {
  final String date;
  final List<_Line> lines;
  final double total;
  const _Night(this.date, this.lines, this.total);
}

class _Resolved {
  final int id;
  final String name;
  final bool isCounter;
  final int quantity;
  final num unitAmount;
  final double? agreedAmount;
  final double amount;
  const _Resolved(this.id, this.name, this.isCounter, this.quantity, this.unitAmount, this.agreedAmount, this.amount);
}

/// "3,5:2@80" is one of charge 3 and two of charge 5 at an agreed ₹80 each —
/// the string the booking form already sends as `chargeIds`.
List<ChargePick> parseChargeSelections(String? raw) {
  final picks = <ChargePick>[];
  for (final part in (raw ?? '').split(',')) {
    if (part.trim().isEmpty) continue;
    final priceSplit = part.split('@');
    final spec = priceSplit.first.split(':');
    final id = num.tryParse(spec[0].trim());
    final qty = spec.length > 1 ? num.tryParse(spec[1].trim()) : 1;
    final agreed = priceSplit.length > 1 && priceSplit[1].trim().isNotEmpty
        ? num.tryParse(priceSplit[1].trim())
        : null;
    if (id == null) continue;
    picks.add(_Raw(id, qty, agreed).toPick()!);
  }
  return normalizeSelections(picks);
}

class _Raw {
  final num id;
  final num? qty;
  final num? agreed;
  _Raw(this.id, this.qty, this.agreed);
  ChargePick? toPick() => ChargePick(id.toInt(), (qty ?? 1).floor(), agreed?.toDouble());
}

/// The same id arriving twice is the desk asking for more of it. A quantity
/// below one, or an id that is not a positive integer, is dropped; a negative
/// or non-numeric agreed price falls back to the lodge's own.
List<ChargePick> normalizeSelections(List<ChargePick> input) {
  final byId = <int, ChargePick>{};
  for (final s in input) {
    if (s.id <= 0 || s.quantity < 1) continue;
    final agreed = s.agreedAmount != null && s.agreedAmount!.isFinite && s.agreedAmount! >= 0
        ? round2(s.agreedAmount!)
        : null;
    final prev = byId[s.id];
    byId[s.id] = ChargePick(
      s.id,
      (prev?.quantity ?? 0) + s.quantity,
      agreed ?? prev?.agreedAmount,
    );
  }
  return byId.values.toList();
}

class StayPricing {
  StayPricing._();

  static String _baseLabel(String categoryName, num categoryBase, num price) {
    final suffix = price == categoryBase ? '' : ' (custom)';
    return '$categoryName ${money(price)}$suffix';
  }

  static String _seasonLabel(PricingSeason s) =>
      '${s.name} (${s.percent > 0 ? '+' : ''}${_trim(s.percent)}%)';

  // JS prints 25 as "25", 12.5 as "12.5", 33.33 as "33.33".
  static String _trim(num n) {
    final s = n.toString();
    return s.endsWith('.0') ? s.substring(0, s.length - 2) : s;
  }

  static String _chargeLabel(_Resolved c) {
    if (c.agreedAmount != null) {
      return c.quantity > 1 ? '${c.name} × ${c.quantity}' : c.name;
    }
    return c.isCounter || c.quantity > 1
        ? '${c.name} ${c.quantity} × ${money(c.unitAmount)}'
        : '${c.name} ${money(c.unitAmount)}';
  }

  static List<_Resolved> _resolve(
    List<PricingCharge> master,
    List<ChargePick> picks,
  ) {
    final wanted = normalizeSelections(picks);
    if (wanted.isEmpty) return const [];
    final byId = {for (final w in wanted) w.id: w};
    final picked = master.where((c) => byId.containsKey(c.id)).toList();

    // A "hide when" extra can't ride along with the extra that hides it.
    for (final row in picked) {
      if (row.hiddenWhenChargeId == null) continue;
      final hider = picked.where((p) => p.id == row.hiddenWhenChargeId);
      if (hider.isNotEmpty) {
        throw PricingUnsupported(
          '“${row.name}” can\'t be combined with “${hider.first.name}”.',
        );
      }
    }

    return picked.map((row) {
      final sel = byId[row.id]!;
      return _Resolved(
        row.id,
        row.name,
        row.isCounter,
        sel.quantity,
        row.chargePerNight,
        sel.agreedAmount,
        sel.agreedAmount != null
            ? round2(sel.agreedAmount!)
            : round2(row.chargePerNight * sel.quantity),
      );
    }).toList();
  }

  static _Night _priceNight(
    String categoryName,
    num categoryBase,
    List<PricingSeason> seasons,
    List<_Resolved> charges,
    String date,
    num? basePriceOverride,
  ) {
    final rate = (basePriceOverride != null && basePriceOverride > 0)
        ? basePriceOverride
        : categoryBase;
    final lines = <_Line>[
      _Line(_baseLabel(categoryName, categoryBase, rate), rate.toDouble(), isBase: true),
    ];
    double subtotal = rate.toDouble();

    for (final s in seasons) {
      if (date.compareTo(s.startDate) < 0 || date.compareTo(s.endDate) > 0) continue;
      final amount = round2(subtotal * (s.percent / 100));
      lines.add(_Line(_seasonLabel(s), amount));
      subtotal += amount;
    }

    // Extras are flat and come after the season: a ₹500 AC charge stays ₹500
    // through a +25% festival, it never compounds with it.
    for (final c in charges) {
      lines.add(_Line(_chargeLabel(c), c.amount, chargeId: c.id, quantity: c.quantity));
      subtotal += c.amount;
    }
    return _Night(date, lines, round2(subtotal));
  }

  /// Quote one ordinary room for a stay. [rooms] data comes from the
  /// bootstrap download; [discount] is clamped to the gross, like the server,
  /// because this also serves the live quote while somebody is still typing.
  static Quote quote({
    required String categoryName,
    required num categoryBasePrice,
    required List<PricingSeason> seasons,
    required List<PricingCharge> charges,
    required List<ChargePick> selections,
    required String checkIn,
    required String checkOut,
    num? basePriceOverride,
    num discount = 0,
  }) {
    final inRange = seasons
        .where((s) => s.startDate.compareTo(checkOut) < 0 && s.endDate.compareTo(checkIn) >= 0)
        .toList()
      ..sort((a, b) => a.startDate.compareTo(b.startDate));
    final resolved = _resolve(charges, selections);

    final nights = datesInRange(checkIn, checkOut)
        .map((d) => _priceNight(categoryName, categoryBasePrice, inRange, resolved, d, basePriceOverride))
        .toList();

    // Seeded in the order a night is priced — base, seasons, extras — so a
    // season that covers only the tail of the stay still reads above the
    // extras instead of wherever the first night happened to put it.
    final totals = <String, _Agg>{};
    final rate = (basePriceOverride != null && basePriceOverride > 0)
        ? basePriceOverride
        : categoryBasePrice;
    final baseLabel = _baseLabel(categoryName, categoryBasePrice, rate);
    for (final label in [baseLabel, ...inRange.map(_seasonLabel)]) {
      totals.putIfAbsent(label, () => _Agg(label, isBase: label == baseLabel));
    }
    for (final c in resolved) {
      totals.putIfAbsent(_chargeLabel(c), () => _Agg(_chargeLabel(c), chargeId: c.id, quantity: c.quantity));
    }
    double total = 0;
    for (final night in nights) {
      for (final line in night.lines) {
        final agg = totals.putIfAbsent(
          line.label,
          () => _Agg(line.label, isBase: line.isBase, chargeId: line.chargeId, quantity: line.quantity),
        );
        agg.amount = round2(agg.amount + line.amount);
        agg.nights += 1;
      }
      total += night.total;
    }
    final gross = round2(total);

    final requested = discount.toDouble();
    final applied = round2(
      (requested.isFinite ? requested : 0).clamp(0, gross).toDouble(),
    );
    final spread = _spreadConcession(nights, gross, applied);

    return Quote(
      charges: [
        for (final a in totals.values)
          if (a.nights > 0)
            QuoteLine(
              label: a.label,
              amount: a.amount,
              isBase: a.isBase,
              chargeId: a.chargeId,
              quantity: a.quantity,
            ),
      ],
      nights: [for (final n in spread) QuoteNight(date: n.date, total: n.total)],
      grossTotal: gross,
      discountAmount: applied,
      totalPrice: round2(gross - applied),
    );
  }

  /// The concession is agreed once on the whole stay and then spread back
  /// across the nights in proportion to what each cost, because everything
  /// downstream (the bill's per-night GST banding) reads the per-night
  /// snapshot. Rounding drift lands on the last night so the nights still sum
  /// to the stay total to the paisa.
  static List<_Night> _spreadConcession(List<_Night> nights, double gross, double discount) {
    if (discount <= 0 || gross <= 0) return nights;
    var remaining = discount;
    final out = <_Night>[];
    for (var i = 0; i < nights.length; i++) {
      final n = nights[i];
      final share = i == nights.length - 1 ? remaining : round2((discount * n.total) / gross);
      remaining = round2(remaining - share);
      out.add(_Night(n.date, [...n.lines, _Line('Concession', -share)], round2(n.total - share)));
    }
    return out;
  }
}

class _Agg {
  final String label;
  double amount = 0;
  int nights = 0;
  final bool isBase;
  final int? chargeId;
  final int? quantity;
  _Agg(this.label, {this.isBase = false, this.chargeId, this.quantity});
}
